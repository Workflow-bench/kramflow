// One-time, idempotent test-operator account for the E2E smoke test
// (e2e/auth-golden-path.spec.ts). Creates the account via Supabase's Admin
// Auth API if it doesn't already exist (safe to re-run — no-ops if it's
// already there), then writes its email/password to .env.test.local
// (gitignored) for Playwright to read.
//
// Run with: node --env-file=.env.local scripts/provision-test-account.mjs
// Requires NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY — the
// same elevated local credentials scripts/seed-mock.mjs already uses.
// This script is meant to be run locally by whoever holds those
// credentials; the password it generates never needs to be shared back —
// it's written straight to a local, gitignored file.

import { randomUUID } from "node:crypto";
import { writeFileSync } from "node:fs";

const URL_BASE = process.env.NEXT_PUBLIC_SUPABASE_URL;
const SERVICE_KEY = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!URL_BASE || !SERVICE_KEY) {
  console.error("Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY");
  process.exit(1);
}

const TEST_EMAIL = "e2e-test-operator@kramflow.test";
const ENV_FILE = ".env.test.local";

async function listUsers() {
  const res = await fetch(`${URL_BASE}/auth/v1/admin/users?per_page=1000`, {
    headers: { apikey: SERVICE_KEY, Authorization: `Bearer ${SERVICE_KEY}` },
  });
  const data = await res.json();
  return data.users ?? [];
}

async function createUser(email, password) {
  const res = await fetch(`${URL_BASE}/auth/v1/admin/users`, {
    method: "POST",
    headers: { apikey: SERVICE_KEY, Authorization: `Bearer ${SERVICE_KEY}`, "Content-Type": "application/json" },
    body: JSON.stringify({ email, password, email_confirm: true, user_metadata: { name: "E2E Test Operator" } }),
  });
  const data = await res.json();
  if (!res.ok) throw new Error(`create user -> ${res.status}: ${JSON.stringify(data)}`);
  return data;
}

const existing = (await listUsers()).find((u) => u.email?.toLowerCase() === TEST_EMAIL);

let password;
if (existing) {
  console.log(`[provision-test-account] ${TEST_EMAIL} already exists (id=${existing.id}) — resetting its password so this run's .env.test.local stays valid.`);
  password = `E2E-${randomUUID()}`;
  const res = await fetch(`${URL_BASE}/auth/v1/admin/users/${existing.id}`, {
    method: "PUT",
    headers: { apikey: SERVICE_KEY, Authorization: `Bearer ${SERVICE_KEY}`, "Content-Type": "application/json" },
    body: JSON.stringify({ password }),
  });
  if (!res.ok) throw new Error(`reset password -> ${res.status}: ${await res.text()}`);
} else {
  password = `E2E-${randomUUID()}`;
  const created = await createUser(TEST_EMAIL, password);
  console.log(`[provision-test-account] created ${TEST_EMAIL} (id=${created.id})`);
}

writeFileSync(
  ENV_FILE,
  `# Generated by scripts/provision-test-account.mjs — gitignored, do not commit.\nE2E_TEST_EMAIL=${TEST_EMAIL}\nE2E_TEST_PASSWORD=${password}\n`
);
console.log(`[provision-test-account] wrote ${ENV_FILE}`);
